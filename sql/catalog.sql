CREATE DATABASE IF NOT EXISTS FINSIGHT;
CREATE SCHEMA IF NOT EXISTS FINSIGHT.RAG;
CREATE TABLE IF NOT EXISTS FINSIGHT.RAG.DOCUMENT_CATALOG (
    SOURCE_FILE VARCHAR(255) NOT NULL,
    COMPANY VARCHAR(20) NOT NULL,
    FILING_YEAR INTEGER NOT NULL,
    CHUNK_COUNT INTEGER DEFAULT 0,
    EMBEDDING_MODEL VARCHAR(255),
    INDEXING_STATUS VARCHAR(20) NOT NULL,
    CONTENT_HASH VARCHAR(64),
    PIPELINE_VERSION VARCHAR(50),
    INDEXED_AT TIMESTAMP_NTZ,
    UPDATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    ERROR_MESSAGE VARCHAR(4000),
    CONSTRAINT PK_DOCUMENT_CATALOG PRIMARY KEY (SOURCE_FILE)
);
